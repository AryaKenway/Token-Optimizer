#!/usr/bin/env node
/*
 * codegraph - builds a navigable graph of a codebase for humans (graph.html)
 * and for AI agents (MAP.md + graph.json + a query CLI), so agents can jump
 * straight to the right file and line range instead of scanning the repo.
 *
 * Zero dependencies (Node >= 16). Usage:
 *   node codegraph.js build [--root .] [--out .codegraph] [--budget 20000]
 *                           [--no-html] [--no-instructions] [--quiet]
 *   node codegraph.js find <words...> [--limit 25]
 *   node codegraph.js sym <name>          definition(s) + callers + callees
 *   node codegraph.js file <path>         everything about one file
 *   node codegraph.js deps <path> [--depth 2]    what it depends on
 *   node codegraph.js rdeps <path> [--depth 2]   what depends on it (impact)
 *   node codegraph.js stale               files changed since last build
 *   node codegraph.js stats
 */
