const HOOK_START = '<!-- codegraph:start -->';
const HOOK_END = '<!-- codegraph:end -->';
function hookBlock() {
  return `${HOOK_START}
## Codebase navigation - read this first
This repo has a generated code graph in \`.codegraph/\`. For any task that involves finding, reading or changing code:
1. Read \`.codegraph/MAP.md\` **before** searching or opening files. It lists every file with a one-line purpose, its dependencies/dependents, and every function/class with exact line ranges.
2. Open only the line ranges you need (Read with offset/limit) instead of whole files; don't run broad Glob/Grep sweeps the map already answers.
3. For precise lookups use the query tool (it refreshes the graph automatically if files changed):
   - \`node .codegraph/codegraph.js find <words>\`: ranked symbols/files with file:line ranges
   - \`node .codegraph/codegraph.js sym <name>\`: definition, callers and callees with line numbers
   - \`node .codegraph/codegraph.js rdeps <path>\`: everything that depends on a file (impact of a change)
   - \`node .codegraph/codegraph.js file <path>\`: all symbols, imports and dependents of one file
4. Treat the graph as an index: confirm against the source lines you open before editing. If \`.codegraph/\` is missing, rebuild it with the \`codegraph\` skill.
${HOOK_END}`;
}
function installHook(root, quiet) {
  const targets = ['CLAUDE.md'];
  for (const extra of ['AGENTS.md', '.github/copilot-instructions.md']) if (fs.existsSync(path.join(root, extra))) targets.push(extra);
  const done = [];
  for (const t of targets) {
    const p = path.join(root, t);
    let txt = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
    const block = hookBlock();
    const s = txt.indexOf(HOOK_START), e = txt.indexOf(HOOK_END);
    let next;
    if (s >= 0 && e > s) next = txt.slice(0, s) + block + txt.slice(e + HOOK_END.length);
    else next = (txt ? txt.replace(/\s*$/, '') + '\n\n' : '') + block + '\n';
    if (next !== txt) { fs.writeFileSync(p, next); done.push(t); }
  }
  return done;
}

