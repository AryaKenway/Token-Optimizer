function extractImports(f, nc) {
  const out = [];
  const add = (spec, line, kind = 'hard', names) => { if (spec) out.push({ spec: spec.trim(), line, kind, names }); };
  const lines = nc.split('\n');
  const L = f.lang;
  const each = (re, fn) => { re.lastIndex = 0; let m; while ((m = re.exec(nc))) fn(m, nc.slice(0, m.index).split('\n').length); };
  if (L === 'js' || L === 'ts') {
    each(/\bimport\s+(?:type\s+)?([\w$*{}\s,]+?)\s+from\s*['"]([^'"\n]+)['"]/g, (m, ln) => add(m[2], ln, 'hard', parseJsNames(m[1])));
    each(/\bexport\s+(?:type\s+)?(?:\*(?:\s+as\s+\w+)?|\{[^}]*\})\s*from\s*['"]([^'"\n]+)['"]/g, (m, ln) => add(m[1], ln));
    each(/\bimport\s*['"]([^'"\n]+)['"]/g, (m, ln) => add(m[1], ln));
    each(/\b(?:require|import)\s*\(\s*['"]([^'"\n]+)['"]\s*\)/g, (m, ln) => add(m[1], ln));
    each(/@import\s+['"]([^'"\n]+)['"]/g, (m, ln) => add(m[1], ln));
  } else if (L === 'py') {
    lines.forEach((l, i) => {
      let m = /^\s*from\s+(\.*[\w.]*)\s+import\s+(.+)$/.exec(l);
      if (m) {
        let names = m[2];
        if (names.includes('(') && !names.includes(')')) { for (let k = i + 1; k < Math.min(lines.length, i + 40); k++) { names += ' ' + lines[k]; if (lines[k].includes(')')) break; } }
        add(m[1], i + 1, 'hard', names.replace(/[()\\]/g, ' ').split(',').map((s) => s.trim().split(/\s+as\s+/)[0].trim()).filter(Boolean));
        return;
      }
      m = /^\s*import\s+(.+)$/.exec(l);
      if (m) for (const part of m[1].split(',')) add(part.trim().split(/\s+as\s+/)[0], i + 1);
    });
  } else if (L === 'go') {
    each(/\bimport\s*\(([^)]*)\)/g, (m, ln) => { m[1].split('\n').forEach((s, k) => { const q = /"([^"]+)"/.exec(s); if (q) add(q[1], ln + k, 'soft'); }); });
    each(/\bimport\s+(?:[\w.]+\s+)?"([^"]+)"/g, (m, ln) => add(m[1], ln, 'soft'));
  } else if (L === 'java' || L === 'kotlin' || L === 'scala') {
    each(/^\s*import\s+(?:static\s+)?(\w+(?:\.\w+)*(?:\.\*)?)/gm, (m, ln) => add(m[1], ln, m[1].endsWith('*') ? 'soft' : 'hard'));
  } else if (L === 'csharp') {
    each(/^\s*(?:global\s+)?using\s+(?:static\s+)?([A-Z][\w.]*)\s*;/gm, (m, ln) => add(m[1], ln, 'soft'));
  } else if (L === 'c' || L === 'cpp') {
    each(/^\s*#\s*include\s*([<"])([^>"]+)[>"]/gm, (m, ln) => add(m[2], ln, m[1] === '"' ? 'hard' : 'sys'));
  } else if (L === 'rust') {
    each(/^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+([A-Za-z_]\w*)\s*;/gm, (m, ln) => add('mod:' + m[1], ln));
    each(/^\s*(?:pub(?:\([^)]*\))?\s+)?use\s+([^;]+);/gm, (m, ln) => { for (const p of expandRustUse(m[1].replace(/\s+/g, ''))) add(p, ln); });
  } else if (L === 'ruby') {
    each(/\brequire_relative\s*\(?\s*['"]([^'"]+)['"]/g, (m, ln) => add('./' + m[1], ln));
    each(/\b(?:require|load)\s*\(?\s*['"]([^'"]+)['"]/g, (m, ln) => add(m[1], ln));
  } else if (L === 'php') {
    each(/\b(?:require|include)(?:_once)?\s*\(?\s*(?:__DIR__\s*\.\s*)?['"]([^'"]+)['"]/g, (m, ln) => add(m[1], ln));
    each(/^\s*use\s+([\w\\]+)(?:\s+as\s+\w+)?\s*;/gm, (m, ln) => add('ns:' + m[1], ln));
  } else if (L === 'shell') {
    each(/^\s*(?:source|\.)\s+["']?([^\s"';]+)/gm, (m, ln) => add(m[1].replace(/^\$\{?(?:SCRIPT_DIR|DIR|BASEDIR)\}?\//, './'), ln));
  } else if (L === 'lua') {
    each(/\brequire\s*\(?\s*['"]([^'"]+)['"]/g, (m, ln) => add(m[1], ln));
  } else if (L === 'dart') {
    each(/^\s*(?:import|export|part)\s+['"]([^'"]+)['"]/gm, (m, ln) => add(m[1], ln));
  } else if (L === 'css') {
    each(/@(?:import|use|forward)\s+(?:url\()?['"]([^'"]+)['"]/g, (m, ln) => add(m[1], ln));
  } else if (L === 'swift') {
    // module imports only; same-directory files are treated as soft candidates
  }
  return out;
}
function parseJsNames(clause) {
  const names = [];
  const braces = /\{([^}]*)\}/.exec(clause);
  if (braces) for (const p of braces[1].split(',')) { const n = p.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0].trim(); if (n) names.push(n); }
  const def = clause.replace(/\{[^}]*\}/, '').replace(/\*\s+as\s+\w+/, '').split(',')[0].trim();
  if (def && /^[\w$]+$/.test(def)) names.push('default:' + def);
  return names;
}
function expandRustUse(u) {
  const i = u.indexOf('{');
  if (i < 0) return [u.replace(/::\*$/, '').replace(/\s+as\s+\w+$/, '')];
  const prefix = u.slice(0, i);
  const inner = u.slice(i + 1, u.lastIndexOf('}'));
  const parts = []; let depth = 0, cur = '';
  for (const ch of inner) { if (ch === '{') depth++; if (ch === '}') depth--; if (ch === ',' && depth === 0) { parts.push(cur); cur = ''; } else cur += ch; }
  if (cur) parts.push(cur);
  return parts.flatMap((p) => (p === 'self' ? [prefix.replace(/::$/, '')] : expandRustUse(prefix + p)));
}

// ───────────────────────────── resolution ─────────────────────────────

class Resolver {
  constructor(root, files) {
    this.root = root;
    this.files = files;
    this.byPath = new Map(files.map((f) => [f.path, f]));
    this.byLower = new Map(files.map((f) => [f.path.toLowerCase(), f]));
    this.byDir = new Map();
    this.byBase = new Map();
    for (const f of files) {
      const d = path.posix.dirname(f.path);
      if (!this.byDir.has(d)) this.byDir.set(d, []);
      this.byDir.get(d).push(f);
      const b = path.posix.basename(f.path).toLowerCase();
      if (!this.byBase.has(b)) this.byBase.set(b, []);
      this.byBase.get(b).push(f);
    }
    this.loadTsconfigs();
    this.loadGoMods();
    this.pyIndex = null;
  }
  get(p) { p = path.posix.normalize(p).replace(/^\.\//, ''); return this.byPath.get(p) || this.byLower.get(p.toLowerCase()); }
  suffix(s) {
    s = s.replace(/^\/+/, '');
    const b = path.posix.basename(s).toLowerCase();
    const c = (this.byBase.get(b) || []).filter((f) => f.path.toLowerCase() === s.toLowerCase() || f.path.toLowerCase().endsWith('/' + s.toLowerCase()));
    return c.length ? c.sort((a, b2) => a.path.length - b2.path.length)[0] : null;
  }
  loadTsconfigs() {
    this.aliases = [];
    for (const f of this.files) {
      if (!/(^|\/)(tsconfig|jsconfig)[\w.]*\.json$/.test(f.path)) continue;
      const j = readJson(path.join(this.root, f.path));
      const co = j && j.compilerOptions;
      if (!co) continue;
      const dir = path.posix.dirname(f.path);
      const baseUrl = path.posix.normalize(path.posix.join(dir, co.baseUrl || '.'));
      for (const [k, targets] of Object.entries(co.paths || {})) {
        this.aliases.push({ dir, prefix: k.replace(/\*$/, ''), wildcard: k.endsWith('*'), targets: (targets || []).map((t) => path.posix.join(baseUrl, t.replace(/\*$/, ''))) });
      }
      if (co.baseUrl) this.aliases.push({ dir, prefix: '', wildcard: true, targets: [baseUrl], base: true });
    }
    this.aliases.sort((a, b) => b.prefix.length - a.prefix.length);
  }
  loadGoMods() {
    this.goMods = [];
    for (const f of this.files) {
      if (!/(^|\/)go\.mod$/.test(f.path)) continue;
      try { const m = /^module\s+(\S+)/m.exec(fs.readFileSync(path.join(this.root, f.path), 'utf8')); if (m) this.goMods.push({ mod: m[1], dir: path.posix.dirname(f.path) }); } catch { }
    }
  }
  tryJs(base) {
    const exts = ['', '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.mts', '.cts', '.vue', '.svelte', '.d.ts', '.json', '.css', '.scss'];
    for (const e of exts) { const f = this.get(base + e); if (f) return f; }
    const swapped = base.replace(/\.(m|c)?js(x)?$/, '');
    if (swapped !== base) for (const e of ['.ts', '.tsx', '.mts', '.cts']) { const f = this.get(swapped + e); if (f) return f; }
    for (const e of ['.ts', '.tsx', '.js', '.jsx', '.mjs', '.vue']) { const f = this.get(base + '/index' + e); if (f) return f; }
    return null;
  }
  resolve(imp, from) {
    const spec = imp.spec;
    const dir = path.posix.dirname(from.path);
    const L = from.lang;
    const rel = (p) => path.posix.normalize(path.posix.join(dir, p));
    if (L === 'js' || L === 'ts' || L === 'css') {
      if (spec.startsWith('.')) return { files: [this.tryJs(rel(spec)) || (L === 'css' ? this.tryCss(rel(spec)) : null)] };
      if (spec.startsWith('/')) return { files: [this.tryJs(spec.slice(1))] };
      for (const a of this.aliases) {
        if (a.dir !== '.' && !from.path.startsWith(a.dir + '/')) continue;
        if (a.wildcard ? spec.startsWith(a.prefix) : spec === a.prefix) {
          const restPart = spec.slice(a.prefix.length);
          for (const t of a.targets) { const f = this.tryJs(path.posix.join(t, restPart)); if (f) return { files: [f] }; }
        }
      }
      for (const [pre, rep] of [['@/', 'src/'], ['~/', 'src/'], ['@/', ''], ['~/', ''], ['src/', 'src/']]) {
        if (spec.startsWith(pre)) { const f = this.tryJs(rep + spec.slice(pre.length)); if (f) return { files: [f] }; }
      }
      if (L === 'css') { const f = this.tryCss(rel(spec)); if (f) return { files: [f] }; }
      return { external: spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0] };
    }
    if (L === 'py') return this.resolvePy(imp, from);
    if (L === 'go') {
      for (const g of this.goMods) {
        if (spec === g.mod || spec.startsWith(g.mod + '/')) {
          const d = path.posix.normalize(path.posix.join(g.dir, spec.slice(g.mod.length)));
          const fs2 = (this.byDir.get(d) || []).filter((f) => f.lang === 'go' && !f.path.endsWith('_test.go'));
          return { files: fs2, soft: true };
        }
      }
      return { external: spec.split('/').slice(0, 3).join('/') };
    }
    if (L === 'java' || L === 'kotlin' || L === 'scala') {
      if (!this.jvmIndex) this.buildJvmIndex();
      const extName = (sp) => { const p = sp.replace(/\.\*$/, '').split('.'); return (/^(com|org|net|io|dev|me|co|edu|gov|uk|de)$/.test(p[0]) ? p.slice(0, 2) : p.slice(0, 1)).join('.'); };
      if (spec.endsWith('*')) { const pk = spec.slice(0, -2); const fsx = this.jvmPkg.get(pk); return fsx ? { files: fsx, soft: true } : { external: extName(spec) }; }
      let s = spec;
      while (s.includes('.')) { const f = this.jvmIndex.get(s); if (f) return { files: [f] }; s = s.slice(0, s.lastIndexOf('.')); }
      return { external: extName(spec) };
    }
    if (L === 'csharp') {
      if (!this.nsIndex) this.buildNsIndex();
      const fsx = this.nsIndex.get(spec);
      return fsx ? { files: fsx, soft: true } : { external: spec.split('.')[0] };
    }
    if (L === 'c' || L === 'cpp') {
      const f = this.get(rel(spec)) || this.get(spec) || this.suffix(spec);
      return f ? { files: [f] } : (imp.kind === 'sys' ? { external: spec.replace(/\.h(pp)?$/, '') } : {});
    }
    if (L === 'rust') return this.resolveRust(spec, from);
    if (L === 'ruby') {
      const s = spec.endsWith('.rb') ? spec : spec + '.rb';
      if (spec.startsWith('.')) return { files: [this.get(rel(s))] };
      const f = this.get('lib/' + s) || this.get(s) || this.suffix(s);
      return f ? { files: [f] } : { external: spec.split('/')[0] };
    }
    if (L === 'php') {
      if (spec.startsWith('ns:')) {
        const parts = spec.slice(3).split('\\');
        for (let k = 0; k < parts.length - 1; k++) { const f = this.suffix(parts.slice(k).join('/') + '.php'); if (f) return { files: [f] }; }
        return { external: parts[0] };
      }
      return { files: [this.get(rel(spec)) || this.get(spec)] };
    }
    if (L === 'shell') return { files: [this.get(rel(spec)) || this.get(spec)] };
    if (L === 'lua') { const p = spec.replace(/\./g, '/'); return { files: [this.get(p + '.lua') || this.get(p + '/init.lua') || this.suffix(p + '.lua')] }; }
    if (L === 'dart') {
      if (spec.startsWith('dart:')) return { external: spec };
      if (spec.startsWith('package:')) { const p = spec.slice(8).split('/'); const f = this.get('lib/' + p.slice(1).join('/')) || this.suffix(p.slice(1).join('/')); return f ? { files: [f] } : { external: p[0] }; }
      return { files: [this.get(rel(spec))] };
    }
    return {};
  }
  tryCss(base) {
    const d = path.posix.dirname(base), b = path.posix.basename(base);
    for (const c of [base, base + '.css', base + '.scss', base + '.sass', base + '.less', d + '/_' + b + '.scss', d + '/_' + b]) { const f = this.get(c); if (f) return f; }
    return null;
  }
  buildPyIndex() {
    this.pyIndex = new Map();
    for (const f of this.files) {
      if (f.lang !== 'py') continue;
      let mod = f.path.replace(/\.pyi?$/, '').replace(/\/__init__$/, '');
      const parts = mod.split('/');
      for (let k = 0; k < parts.length; k++) {
        const name = parts.slice(k).join('.');
        if (!this.pyIndex.has(name)) this.pyIndex.set(name, []);
        this.pyIndex.get(name).push({ f, k });
      }
    }
  }
  resolvePy(imp, from) {
    if (!this.pyIndex) this.buildPyIndex();
    const spec = imp.spec;
    const lookupMod = (name) => { const c = this.pyIndex.get(name); if (!c) return null; return c.slice().sort((a, b) => a.k - b.k || sharedPrefix(b.f.path, from.path) - sharedPrefix(a.f.path, from.path))[0].f; };
    const pkgFile = (dirPath) => this.get(dirPath + '/__init__.py');
    if (spec.startsWith('.')) {
      const level = /^\.+/.exec(spec)[0].length;
      let base = path.posix.dirname(from.path);
      for (let k = 1; k < level; k++) base = path.posix.dirname(base);
      const rest = spec.slice(level).replace(/\./g, '/');
      const modPath = rest ? path.posix.join(base, rest) : base;
      const files = [];
      for (const n of imp.names || []) { const f = this.get(modPath + '/' + n + '.py') || pkgFile(modPath + '/' + n); if (f) files.push(f); }
      const m = this.get(modPath + '.py') || pkgFile(modPath);
      if (m) files.push(m);
      return { files };
    }
    const files = [];
    for (const n of imp.names || []) { const f = lookupMod(spec + '.' + n); if (f) files.push(f); }
    const m = lookupMod(spec);
    if (m) files.push(m);
    if (files.length) return { files };
    return { external: spec.split('.')[0] };
  }
  buildJvmIndex() {
    this.jvmIndex = new Map(); this.jvmPkg = new Map();
    for (const f of this.files) {
      if (!['java', 'kotlin', 'scala'].includes(f.lang)) continue;
      const pk = f._pkg || '';
      const stem = path.posix.basename(f.path).replace(/\.\w+$/, '');
      this.jvmIndex.set(pk ? pk + '.' + stem : stem, f);
      for (const s of f._symsTop || []) this.jvmIndex.set(pk ? pk + '.' + s : s, f);
      if (!this.jvmPkg.has(pk)) this.jvmPkg.set(pk, []);
      this.jvmPkg.get(pk).push(f);
    }
  }
  buildNsIndex() {
    this.nsIndex = new Map();
    for (const f of this.files) for (const ns of f._ns || []) { if (!this.nsIndex.has(ns)) this.nsIndex.set(ns, []); this.nsIndex.get(ns).push(f); }
  }
  resolveRust(spec, from) {
    const dir = path.posix.dirname(from.path);
    const stem = path.posix.basename(from.path, '.rs');
    const modDir = ['mod', 'lib', 'main'].includes(stem) ? dir : dir + '/' + stem;
    const tryMod = (d, name) => this.get(d + '/' + name + '.rs') || this.get(d + '/' + name + '/mod.rs');
    if (spec.startsWith('mod:')) return { files: [tryMod(modDir, spec.slice(4))] };
    const segs = spec.split('::');
    let baseDir;
    if (segs[0] === 'crate') {
      let d = dir; while (d !== '.' && !this.get(d + '/Cargo.toml') && !this.get(d + '/cargo.toml')) d = path.posix.dirname(d);
      baseDir = (d === '.' ? '' : d + '/') + 'src'; segs.shift();
    } else if (segs[0] === 'super') { baseDir = path.posix.dirname(modDir); while (segs[0] === 'super') { segs.shift(); if (segs[0] === 'super') baseDir = path.posix.dirname(baseDir); } }
    else if (segs[0] === 'self') { baseDir = modDir; segs.shift(); }
    else {
      const f = tryMod(modDir, segs[0]);
      if (!f) return { external: segs[0] };
      baseDir = modDir;
    }
    for (let k = segs.length; k > 0; k--) { const p = segs.slice(0, k - 1).join('/'); const f = tryMod(p ? baseDir + '/' + p : baseDir, segs[k - 1]); if (f) return { files: [f] }; }
    const own = this.get(baseDir + '/lib.rs') || this.get(baseDir + '/main.rs') || this.get(baseDir + '/mod.rs');
    return own ? { files: [own] } : {};
  }
}
function sharedPrefix(a, b) { let i = 0; while (i < a.length && a[i] === b[i]) i++; return i; }

// ───────────────────────────── build ─────────────────────────────

function build(root, opts = {}) {
  const t0 = Date.now();
  root = path.resolve(root);
  const { files, warnings } = walk(root);
  const parsed = [];
  let generated = 0;
  for (const f of files) {
    let raw;
    try { raw = fs.readFileSync(path.join(root, f.path), 'utf8'); } catch { continue; }
    if (raw.includes('\u0000')) continue;
    if (f.cat !== 'config' && GENERATED_RE.test(raw.slice(0, 600))) { generated++; continue; }
    raw = raw.replace(/^﻿/, '').replace(/\r\n?/g, '\n');
    f.lines = raw.length ? raw.split('\n').length - (raw.endsWith('\n') ? 1 : 0) : 0;
    const L = LANGS[f.lang] || { line: [], block: [], quotes: '' };
    const { nc, code } = (f.cat === 'config' || f.lang === 'md') ? { nc: raw, code: raw } : mask(raw, L);
    const rawLines = raw.split('\n');
    f.summary = fileSummary(rawLines, f.lang, f.cat);
    try { f.syms = extractSymbols(f, raw, code); } catch (e) { f.syms = []; warnings.push(`parse error in ${f.path}: ${e.message}`); }
    f.imports = f.cat === 'config' || f.lang === 'md' ? [] : extractImports(f, nc);
    if (['java', 'kotlin', 'scala'].includes(f.lang)) { const m = /^\s*package\s+([\w.]+)/m.exec(code); f._pkg = m ? m[1] : ''; f._symsTop = f.syms.filter((s) => !s.parent).map((s) => s.name); }
    if (f.lang === 'csharp') { f._ns = []; code.replace(/^\s*namespace\s+([\w.]+)/gm, (_, ns) => { f._ns.push(ns); }); }
    f._code = (f.cat === 'code' || f.cat === 'test') ? code : '';
    f._main = /\bif\s+__name__\s*==\s*['"]__main__['"]|^func\s+main\s*\(|\bstatic\s+void\s+Main\s*\(|\bpublic\s+static\s+void\s+main\s*\(|^\s*fn\s+main\s*\(|^int\s+main\s*\(|\bapp\.listen\s*\(|\bcreateRoot\s*\(|ReactDOM\.render\s*\(/m.test(code);
    parsed.push(f);
  }

  if (generated) warnings.push(`skipped ${generated} generated file(s)`);
  const R = new Resolver(root, parsed);
  // ids
  parsed.forEach((f, i) => { f.id = i; });
  const syms = [];
  for (const f of parsed) for (const s of f.syms) { s.id = syms.length; s.file = f.id; syms.push(s); }

  // resolve imports
  for (const f of parsed) {
    f.hard = new Set(); f.soft = new Set(); f.ext = new Set();
    for (const imp of f.imports) {
      let r = {};
      try { r = R.resolve(imp, f) || {}; } catch { r = {}; }
      if (r.external) { if (!/^(\.|node:)/.test(r.external)) f.ext.add(r.external.replace(/^node:/, '')); continue; }
      for (const t of r.files || []) if (t && t.id !== f.id) ((r.soft || imp.kind === 'soft') ? f.soft : f.hard).add(t.id);
    }
    // implicit same-package visibility
    const dir = path.posix.dirname(f.path);
    if (['go', 'java', 'kotlin', 'scala', 'swift', 'csharp'].includes(f.lang)) {
      for (const g of R.byDir.get(dir) || []) if (g.id !== f.id && g.lang === f.lang) f.soft.add(g.id);
    }
    if (f.lang === 'csharp' && f._ns.length) {
      if (!R.nsIndex) R.buildNsIndex();
      for (const ns of f._ns) { const parts = ns.split('.'); for (let k = parts.length; k > 0; k--) for (const g of R.nsIndex.get(parts.slice(0, k).join('.')) || []) if (g.id !== f.id) f.soft.add(g.id); }
    }
    if (f.lang === 'c' || f.lang === 'cpp') {
      const stem = f.path.replace(/\.\w+$/, '');
      for (const g of R.byDir.get(dir) || []) if (g.id !== f.id && g.path.replace(/\.\w+$/, '') === stem) f.soft.add(g.id);
    }
  }

  // references (approximate call/use graph)
  const refAgg = new Map(); // key fromSym|fromFile|toSym → {line,count}
  for (const f of parsed) {
    if (!f._code) continue;
    const cand = new Map();
    const addSyms = (fid, sameFile) => {
      for (const s of parsed[fid].syms) {
        if (s.kind === 'heading' || s.kind === 'target' || s.kind === 'script' || s.name.length < 2) continue;
        const isMember = s.kind === 'method';
        if (isMember && !sameFile && (s.name.length < 4 || GENERIC_METHODS.has(s.name.toLowerCase()))) continue;
        if (!sameFile && s.exported === false && f.lang !== 'csharp' && f.lang !== 'java') continue;
        if (!cand.has(s.name)) cand.set(s.name, s);
      }
    };
    addSyms(f.id, true);
    for (const id of f.hard) addSyms(id, false);
    for (const id of f.soft) addSyms(id, false);
    if (!cand.size) continue;
    // innermost enclosing symbol per line
    const owner = new Int32Array(f.lines + 2).fill(-1);
    const bySize = f.syms.filter((s) => s.kind !== 'heading').slice().sort((a, b) => (b.end - b.line) - (a.end - a.line));
    for (const s of bySize) for (let l = s.line; l <= Math.min(s.end, f.lines + 1); l++) owner[l] = s.id;
    const lines = f._code.split('\n');
    const idRe = /[A-Za-z_$][\w$]*/g;
    for (let li = 0; li < lines.length; li++) {
      const ln = lines[li];
      if (!ln.trim()) continue;
      idRe.lastIndex = 0;
      let m;
      while ((m = idRe.exec(ln))) {
        const s = cand.get(m[0]);
        if (!s) continue;
        if (s.file === f.id && s.line === li + 1) continue;
        const prev = ln.slice(0, m.index).trimEnd();
        const member = /(\.|->|::|\?\.)$/.test(prev);
        if (s.kind === 'method' && s.file !== f.id && !member) continue;
        if (/^(import|from|using|#\s*include|use|package|require)\b/.test(ln.trim()) ) continue;
        const fromSym = owner[li + 1];
        if (fromSym === s.id) continue;
        const key = fromSym + '|' + f.id + '|' + s.id;
        const e = refAgg.get(key);
        if (e) e.count++; else refAgg.set(key, { from: fromSym, file: f.id, to: s.id, line: li + 1, count: 1 });
      }
    }
  }
  const refs = [...refAgg.values()];

  // file edges
  const edgeMap = new Map();
  const addEdge = (a, b, kind) => { if (a === b) return; const k = a + '>' + b; const e = edgeMap.get(k) || { s: a, t: b, imp: 0, refs: 0 }; if (kind === 'imp') e.imp = 1; else e.refs++; edgeMap.set(k, e); };
  for (const f of parsed) for (const t of f.hard) addEdge(f.id, t, 'imp');
  for (const r of refs) addEdge(r.file, syms[r.to].file, 'ref');
  // soft package imports with no resolved refs still deserve one edge when small
  for (const f of parsed) {
    if (f.lang === 'csharp') continue; // `using X;` only names a namespace; rely on resolved refs
    for (const imp of f.imports) if (imp.kind === 'soft') {
      let r = {}; try { r = R.resolve(imp, f) || {}; } catch { }
      const tg = (r.files || []).filter(Boolean);
      if (tg.length && !tg.some((t) => edgeMap.has(f.id + '>' + t.id)) && tg.length <= 5) for (const t of tg) addEdge(f.id, t.id, 'imp');
    }
  }
  const edges = [...edgeMap.values()];

  const out = {
    version: VERSION,
    generated: new Date().toISOString(),
    root,
    name: path.basename(root),
    buildMs: 0,
    warnings,
    files: parsed.map((f) => ({
      p: f.path, lang: f.lang, cat: f.cat, lines: f.lines, size: f.size, mtime: f.mtime, sum: f.summary || '',
      ext: [...f.ext].sort(), main: f._main ? 1 : 0,
    })),
    syms: syms.map((s) => {
      const o = { f: s.file, n: s.name, k: s.kind, l: s.line, e: s.end };
      if (s.sig) o.sig = s.sig;
      if (s.doc) o.doc = s.doc;
      if (s.parent) o.p = s.parent.id;
      if (s.owner) o.o = s.owner;
      if (s.route) o.r = s.route;
      if (s.level) o.lv = s.level;
      if (s.exported === false) o.priv = 1;
      return o;
    }),
    edges,
    refs: refs.map((r) => [r.from, r.file, r.to, r.line, r.count]),
  };
  out.buildMs = Date.now() - t0;
  return out;
}

