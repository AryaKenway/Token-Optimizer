function displaySig(g, s, max) {
  if (s.k === 'script') return clip(s.sig || s.n, max || 120);
  let label = s.sig || symLabel(g, s);
  if (s.o && s.sig && !label.includes(s.o)) label = s.o + '.' + label;
  if (max) label = clip(label, max);
  return (s.r ? `[${s.r}] ` : '') + label;
}

function vendorRoots(g) {
  const roots = new Map();
  for (const f of g.files) {
    if (f.cat !== 'vendor') continue;
    const m = VENDOR_RE.exec(f.p) || EXAMPLE_RE.exec(f.p);
    const root = m ? f.p.slice(0, m.index + m[0].length).replace(/\/$/, '') : dirOf(f.p);
    roots.set(root, (roots.get(root) || 0) + 1);
  }
  return [...roots.entries()].sort((a, b) => b[1] - a[1]);
}

function renderTree(g, maxLines) {
  const mk = (name) => ({ name, kids: new Map(), direct: 0, files: 0, vendor: 0 });
  const root = mk('');
  for (const f of g.files) {
    const parts = f.p.split('/'); parts.pop();
    let n = root;
    for (const p of parts) { if (!n.kids.has(p)) n.kids.set(p, mk(p)); n = n.kids.get(p); n.files++; if (f.cat === 'vendor') n.vendor++; }
    n.direct++;
  }
  const out = [];
  const rec = (n, depth, maxDepth) => {
    for (const k of [...n.kids.values()].sort((a, b) => (a.name < b.name ? -1 : 1))) {
      let name = k.name, node = k;
      while (node.direct === 0 && node.kids.size === 1) { node = [...node.kids.values()][0]; name += '/' + node.name; }
      const allVendor = node.vendor === node.files;
      out.push(`${'  '.repeat(depth)}${name}/ (${node.files}${allVendor ? ', vendor' : ''})`);
      if (depth + 1 < maxDepth && !allVendor) rec(node, depth + 1, maxDepth);
    }
  };
  for (let maxDepth = 8; maxDepth >= 1; maxDepth--) { out.length = 0; rec(root, 0, maxDepth); if (out.length <= maxLines) break; }
  if (root.direct && out.length) out.unshift(`./ (${root.direct} at root)`);
  return out;
}

function renderHeader(g, level) {
  const L = [];
  const codeFiles = g.files.filter((f) => f.cat === 'code' || f.cat === 'test');
  L.push(`# Code map: ${g.name}`);
  L.push(`${g.files.length} files | ${g.syms.length} symbols | ${g.edges.length} file deps | built ${g.generated.slice(0, 16).replace('T', ' ')} UTC | detail ${level}`);
  L.push('');
  L.push('Use: locate the file/symbol here, then read ONLY its line range (Read offset=START, limit=END-START+1). Skip repo-wide grep/glob when this map answers it.');
  L.push(`Query (auto-refreshes if files changed): \`${TOOL} find <words>\` | \`sym <name>\` (def + callers + callees) | \`file <path>\` | \`rdeps <path>\` (impact) | \`deps <path>\``);
  L.push('Format: `uses:` files this one imports/calls, `used by:` dependents, `tests:` test files; `./x` = same folder. Symbols: `kind signature START-END` (1-based, inclusive); members indented under their type.');
  L.push('');
  L.push('## Overview');
  const langCount = {};
  for (const f of codeFiles) langCount[f.lang] = (langCount[f.lang] || 0) + 1;
  L.push('Languages: ' + Object.entries(langCount).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', '));
  const entries = g.files.map((f, i) => ({ f, i })).filter(({ f, i }) => f.cat === 'code' && (f.main || (g.in[i].length === 0 && /(^|\/)(main|index|app|server|cli|__main__|program|manage|run)\.\w+$/i.test(f.p))));
  if (entries.length) L.push('Entry points: ' + entries.slice(0, 12).map(({ f }) => f.p).join(', ') + (entries.length > 12 ? ` (+${entries.length - 12})` : ''));
  const hubs = g.files.map((f, i) => ({ f, n: new Set(g.in[i].filter((j) => g.files[j].cat === 'code')).size })).filter((x) => x.n >= 3 && x.f.cat === 'code').sort((a, b) => b.n - a.n).slice(0, 10);
  if (hubs.length) L.push('Most depended-on: ' + hubs.map((h) => `${h.f.p} (${h.n})`).join(', '));
  const extCount = {};
  for (const f of g.files) if (f.cat !== 'vendor') for (const e of f.ext) extCount[e] = (extCount[e] || 0) + 1;
  const exts = Object.entries(extCount).sort((a, b) => b[1] - a[1]);
  if (exts.length) L.push('External packages: ' + exts.slice(0, 25).map(([k]) => k).join(', ') + (exts.length > 25 ? ` (+${exts.length - 25})` : ''));
  const cfg = g.files.filter((f) => f.cat === 'config');
  if (cfg.length) L.push('Config: ' + cfg.slice(0, 20).map((f) => f.p).join(', '));
  const vr = vendorRoots(g);
  if (vr.length) L.push('Vendor/third-party (not detailed below; use find/sym/file): ' + vr.slice(0, 15).map(([r, n]) => `${r}/ (${n})`).join(', ') + (vr.length > 15 ? ` (+${vr.length - 15})` : ''));
  L.push('');
  const tree = renderTree(g, level >= 3 ? 60 : 120);
  if (tree.length > 1) { L.push('## Directories (file counts)'); L.push(...tree); L.push(''); }
  return L;
}

function renderFiles(g, level, ids) {
  const L = [];
  let curDir = null;
  const fmtList = (list, max, fromDir) => {
    const u = [...new Set(list)].map((j) => { const p = g.files[j].p; return dirOf(p) === fromDir ? './' + p.slice(p.lastIndexOf('/') + 1) : p; });
    return u.slice(0, max).join(', ') + (u.length > max ? ` (+${u.length - max})` : '');
  };
  for (const i of ids) {
    const f = g.files[i];
    if (!f.lines && !g.out[i].length && !g.in[i].length) continue;
    const d = dirOf(f.p);
    if (d !== curDir) { L.push(''); L.push(`### ${d === '.' ? './' : d + '/'}`); curDir = d; }
    const base = f.p.slice(f.p.lastIndexOf('/') + 1);
    let head = `**${base}** [${f.lines}]`;
    if (f.sum) head += ' - ' + (level >= 3 ? clip(f.sum, 70) : f.sum);
    L.push(head);
    const rel = [];
    const max = level >= 3 ? 4 : 8;
    if (g.out[i].length) rel.push('uses: ' + fmtList(g.out[i], max, d));
    const usedBy = g.in[i].filter((j) => g.files[j].cat !== 'test');
    if (usedBy.length) rel.push('used by: ' + fmtList(usedBy, max, d));
    if (g.testsOf[i].length) rel.push('tests: ' + fmtList(g.testsOf[i], 3, d));
    if (rel.length) L.push('  ' + rel.join(' | '));
    if (level >= 4) continue;
    const syms = g.symsByFile[i];
    if (!syms.length) continue;
    if (f.lang === 'md') {
      if (level >= 3) continue;
      const hs = syms.filter((s) => (s.lv || 1) <= 2);
      if (hs.length) L.push('  ' + hs.slice(0, 12).map((s) => `${s.n} ${range(s)}`).join(' | ') + (hs.length > 12 ? ` (+${hs.length - 12})` : ''));
      continue;
    }
    const top = syms.filter((s) => s.p === undefined);
    const kids = new Map();
    for (const s of syms) if (s.p !== undefined) { if (!kids.has(s.p)) kids.set(s.p, []); kids.get(s.p).push(s); }
    if (level === 3) {
      L.push('  ' + top.map((s) => `${KIND_ABBR[s.k] || s.k} ${s.r ? `[${s.r}] ` : ''}${symLabel(g, s)} ${range(s)}`).join(' | '));
      continue;
    }
    const emit = (s, depth) => {
      const ab = KIND_ABBR[s.k] || s.k;
      const ch = kids.get(s.id) || [];
      let line = `${'  '.repeat(depth + 1)}${ab} ${displaySig(g, s, level === 2 ? 60 : 0)} ${range(s)}`;
      if (level === 0 && s.doc && depth === 0) line += ` - ${s.doc}`;
      if (ch.length && (level >= 2 || ch.length > 30)) { L.push(line + ': ' + ch.map((c) => `${c.n} ${range(c)}`).join(', ')); return; }
      L.push(line);
      for (const c of ch) emit(c, depth + 1);
    };
    for (const s of top) emit(s, 0);
  }
  return L;
}

function writeMaps(g, outDir, budget) {
  const mapDir = path.join(outDir, 'map');
  if (fs.existsSync(mapDir)) for (const old of fs.readdirSync(mapDir)) fs.unlinkSync(path.join(mapDir, old));
  const ids = g.files.map((f, i) => i).filter((i) => g.files[i].cat !== 'vendor').sort(byPathOrder(g));
  for (let level = 0; level <= 4; level++) {
    const md = renderHeader(g, level).concat(['## Files'], renderFiles(g, level, ids)).join('\n');
    if (estTokens(md) <= budget) { fs.writeFileSync(path.join(outDir, 'MAP.md'), md + '\n'); return { level, tokens: estTokens(md), split: 0 }; }
  }
  // Too big for one file: partition by directory subtree, pack small neighbours together.
  const cost = new Map(ids.map((i) => [i, estTokens(renderFiles(g, 1, [i]).join('\n'))]));
  const mk = () => ({ kids: new Map(), direct: [], cost: 0, directCost: 0 });
  const root = mk();
  for (const i of ids) {
    const parts = g.files[i].p.split('/'); parts.pop();
    let n = root; n.cost += cost.get(i);
    for (const p of parts) { if (!n.kids.has(p)) n.kids.set(p, mk()); n = n.kids.get(p); n.cost += cost.get(i); }
    n.direct.push(i); n.directCost += cost.get(i);
  }
  const all = (n) => n.direct.concat(...[...n.kids.values()].map(all));
  const raw = [];
  const part = (n, prefix) => {
    if (n.cost <= budget * 0.9 || (!n.kids.size)) { raw.push({ names: [prefix || './'], ids: all(n), cost: n.cost }); return; }
    if (n.direct.length) raw.push({ names: [(prefix || '.') + '/ (files directly here)'], ids: n.direct, cost: n.directCost });
    for (const [k, c] of [...n.kids.entries()].sort()) part(c, prefix ? prefix + '/' + k : k);
  };
  part(root, '');
  const areas = [];
  for (const a of raw) {
    const last = areas[areas.length - 1];
    if (last && last.cost + a.cost <= budget * 0.9) { last.names.push(...a.names); last.ids.push(...a.ids); last.cost += a.cost; }
    else areas.push({ ...a, names: [...a.names], ids: [...a.ids] });
  }
  fs.mkdirSync(mapDir, { recursive: true });
  const index = [];
  areas.forEach((a, k) => {
    const slug = a.names[0].replace(/\/ \(files directly here\)$/, '').split('/').slice(-2).join('_').replace(/[^\w.-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 50) || 'root';
    const fname = `map/${String(k + 1).padStart(2, '0')}-${slug}.md`;
    const sorted = a.ids.sort(byPathOrder(g));
    let md = '';
    for (let level = 0; level <= 4; level++) {
      md = [`# Code map area: ${a.names.join(', ')}`, `Part of .codegraph/MAP.md (see it for the overview and format). ${sorted.length} files, detail ${level}.`, ...renderFiles(g, level, sorted)].join('\n');
      if (estTokens(md) <= budget) break;
    }
    fs.writeFileSync(path.join(outDir, fname), md + '\n');
    index.push(`- ${a.names.slice(0, 6).join(', ')}${a.names.length > 6 ? ` (+${a.names.length - 6} more)` : ''}: ${sorted.length} files -> .codegraph/${fname}`);
  });
  const md = renderHeader(g, 4).concat(['## Detailed maps by area', 'The repo is too large for one map. Read the area file(s) relevant to the task:'], index).join('\n');
  fs.writeFileSync(path.join(outDir, 'MAP.md'), md + '\n');
  return { level: 'split', tokens: estTokens(md), split: areas.length };
}

