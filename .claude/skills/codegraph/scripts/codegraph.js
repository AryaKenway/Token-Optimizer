function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const eq = a.indexOf('=');
      if (eq > 0) out[a.slice(2, eq)] = a.slice(eq + 1);
      else if (a.startsWith('--no-')) out[a.slice(5)] = false;
      else if (i + 1 < argv.length && !argv[i + 1].startsWith('--') && ['root', 'out', 'budget', 'limit', 'depth'].includes(a.slice(2))) out[a.slice(2)] = argv[++i];
      else out[a.slice(2)] = true;
    } else out._.push(a);
  }
  return out;
}

function lineStartsOf(s) {
  const st = [0];
  for (let i = 0; i < s.length; i++) if (s.charCodeAt(i) === 10) st.push(i + 1);
  return st;
}
function lineOfPos(starts, pos) {
  let lo = 0, hi = starts.length - 1;
  while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (starts[mid] <= pos) lo = mid; else hi = mid - 1; }
  return lo + 1; // 1-based
}

function stripJsonComments(s) {
  return s.replace(/\\"|"(?:\\"|[^"])*"|(\/\/.*|\/\*[\s\S]*?\*\/)/g, (m, g) => (g ? '' : m)).replace(/,(\s*[}\]])/g, '$1');
}
function readJson(p) {
  try { return JSON.parse(stripJsonComments(fs.readFileSync(p, 'utf8').replace(/^﻿/, ''))); } catch { return null; }
}
