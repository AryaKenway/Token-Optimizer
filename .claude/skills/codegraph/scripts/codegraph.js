// ───────────────────────────── .gitignore ─────────────────────────────

function compileGitignore(text, baseRel) {
  const rules = [];
  for (let raw of text.split(/\r?\n/)) {
    let line = raw.replace(/\s+$/, '');
    if (!line || line.startsWith('#')) continue;
    let neg = false;
    if (line.startsWith('!')) { neg = true; line = line.slice(1); }
    if (line.startsWith('\\')) line = line.slice(1);
    let dirOnly = false;
    if (line.endsWith('/')) { dirOnly = true; line = line.slice(0, -1); }
    const anchored = line.includes('/');
    if (line.startsWith('/')) line = line.slice(1);
    let re = '';
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (c === '*') {
        if (line[i + 1] === '*') {
          if (line[i + 2] === '/') { re += '(?:.*/)?'; i += 2; } else { re += '.*'; i++; }
        } else re += '[^/]*';
      } else if (c === '?') re += '[^/]';
      else if (c === '[') { const j = line.indexOf(']', i); if (j > i) { re += line.slice(i, j + 1).replace('[!', '[^'); i = j; } else re += '\\['; }
      else re += /[.+^${}()|\\]/.test(c) ? '\\' + c : c;
    }
    const full = anchored ? `^${re}(?:/.*)?$` : `(?:^|/)${re}(?:/.*)?$`;
    rules.push({ re: new RegExp(full), neg, dirOnly, base: baseRel });
  }
  return rules;
}
function isIgnored(rules, rel, isDir) {
  let ign = false;
  for (const r of rules) {
    let sub = rel;
    if (r.base) { if (!rel.startsWith(r.base + '/')) continue; sub = rel.slice(r.base.length + 1); }
    if (r.dirOnly && !isDir) {
      // a dir-only rule can still match a parent directory of this file
      const parent = sub.includes('/') ? sub.slice(0, sub.lastIndexOf('/')) : '';
      if (!parent || !r.re.test(parent)) continue;
    } else if (!r.re.test(sub)) continue;
    ign = !r.neg;
  }
  return ign;
}

// ───────────────────────────── file walk ─────────────────────────────

function classify(rel) {
  const base = rel.slice(rel.lastIndexOf('/') + 1);
  const lower = base.toLowerCase();
  const ext = path.extname(lower);
  if (IGNORE_FILE_RE.test(lower)) return null;
  if (CONFIG_FILES.has(lower) || /^dockerfile/.test(lower) || /^tsconfig.*\.json$/.test(lower) || /\.csproj$/.test(lower)) {
    return { lang: lower === 'makefile' ? 'make' : lower === 'package.json' ? 'pkgjson' : 'config', cat: 'config' };
  }
  const lang = EXT2LANG[ext];
  if (!lang) return null;
  if (lang === 'md') return { lang, cat: 'doc' };
  if (lang === 'css') return { lang, cat: 'style' };
  if (VENDOR_RE.test(rel) || (EXAMPLE_RE.test(rel) && /(^|\/)Assets\//.test(rel))) return { lang, cat: 'vendor' };
  return { lang, cat: isTestPath(rel) ? 'test' : 'code' };
}

function walk(root) {
  const files = [];
  const warnings = [];
  const rootRules = [];
  const ex = path.join(root, '.git', 'info', 'exclude');
  if (fs.existsSync(ex)) rootRules.push(...compileGitignore(fs.readFileSync(ex, 'utf8'), ''));
  const cgi = path.join(root, '.codegraphignore');
  if (fs.existsSync(cgi)) rootRules.push(...compileGitignore(fs.readFileSync(cgi, 'utf8'), ''));
  let bigSkipped = [];
  (function rec(absDir, relDir, rules) {
    let entries;
    try { entries = fs.readdirSync(absDir, { withFileTypes: true }); } catch { return; }
    const gi = entries.find((e) => e.name === '.gitignore' && e.isFile());
    if (gi) rules = rules.concat(compileGitignore(fs.readFileSync(path.join(absDir, '.gitignore'), 'utf8'), relDir));
    entries.sort((a, b) => (a.name < b.name ? -1 : 1));
    for (const e of entries) {
      if (files.length >= MAX_FILES) { if (!warnings.includes('max')) warnings.push('max'); return; }
      const rel = relDir ? relDir + '/' + e.name : e.name;
      if (e.isDirectory()) {
        if (IGNORE_DIRS.has(e.name) || IGNORE_DIR_RE.test(e.name) || (e.name.startsWith('.') && e.name !== '.github' && e.name !== '.claude')) continue;
        if (isIgnored(rules, rel, true)) continue;
        rec(path.join(absDir, e.name), rel, rules);
      } else if (e.isFile()) {
        const c = classify(rel);
        if (!c || isIgnored(rules, rel, false)) continue;
        let st;
        try { st = fs.statSync(path.join(absDir, e.name)); } catch { continue; }
        if (st.size > MAX_FILE_BYTES) { bigSkipped.push(rel); continue; }
        files.push({ path: rel, ...c, size: st.size, mtime: Math.floor(st.mtimeMs) });
      }
    }
  })(root, '', rootRules);
  if (warnings.includes('max')) warnings[warnings.indexOf('max')] = `stopped at ${MAX_FILES} files`;
  if (bigSkipped.length) warnings.push(`skipped ${bigSkipped.length} file(s) over 1MB (e.g. ${bigSkipped.slice(0, 3).join(', ')})`);
  return { files, warnings };
}

// ───────────────────────────── masking ─────────────────────────────
// Produces two strings of identical length/line layout as the source:
//   nc   - comments blanked (strings kept)      → used for import specs
//   code - comments and string bodies blanked   → used for braces/symbols/identifiers

function mask(src, L) {
  const n = src.length;
  const nc = src.split('');
  const code = src.split('');
  const blank = (arr, a, b) => { for (let k = a; k < b; k++) if (arr[k] !== '\n' && arr[k] !== '\r') arr[k] = ' '; };
  const lineC = L.line || [], blockC = L.block || [], quotes = L.quotes || '';
  let i = 0;
  outer: while (i < n) {
    const ch = src[i];
    for (const [open, close] of blockC) {
      if (src.startsWith(open, i)) {
        let j = src.indexOf(close, i + open.length);
        j = j < 0 ? n : j + close.length;
        blank(nc, i, j); blank(code, i, j); i = j; continue outer;
      }
    }
    for (const lc of lineC) {
      if (src.startsWith(lc, i)) {
        if (lc === '#' && L.hashNeedsSpace && i > 0 && !/\s/.test(src[i - 1])) break;
        if (lc === '#' && L.hashNeedsSpace && src[i + 1] === '!' && i === 0) break; // shebang kept harmlessly
        let j = src.indexOf('\n', i); if (j < 0) j = n;
        blank(nc, i, j); blank(code, i, j); i = j; continue outer;
      }
    }
    if (L.triple && (src.startsWith('"""', i) || src.startsWith("'''", i))) {
      const q = src.substr(i, 3);
      let j = i + 3;
      while (j < n && !src.startsWith(q, j)) j += src[j] === '\\' ? 2 : 1;
      j = Math.min(n, j + 3);
      blank(code, i + 3, j - 3); i = j; continue;
    }
    if (L.rustChars && ch === "'") {
      const m = /^'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]+\}|.)|[^\\'\n])'/.exec(src.slice(i, i + 12));
      if (m) { blank(code, i + 1, i + m[0].length - 1); i += m[0].length; continue; }
      i++; continue; // lifetime
    }
    if (quotes.includes(ch)) {
      const multiline = (L.multilineQuote || '').includes(ch);
      const raw = (L.rawQuote || '').includes(ch);
      let j = i + 1;
      while (j < n && src[j] !== ch) {
        if (src[j] === '\\' && !raw) j++;
        else if (src[j] === '\n' && !multiline) break;
        j++;
      }
      blank(code, i + 1, Math.min(j, n)); i = Math.min(n, j + 1); continue;
    }
    i++;
  }
  return { nc: nc.join(''), code: code.join('') };
}

