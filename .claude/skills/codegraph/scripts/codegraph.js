function locate(args) {
  if (args.root) { const r = path.resolve(args.root); return { root: r, out: path.join(r, args.out || DEFAULT_OUT) }; }
  const selfDir = path.dirname(__filename);
  if (fs.existsSync(path.join(selfDir, 'graph.json'))) return { root: path.dirname(selfDir), out: selfDir };
  let d = process.cwd();
  for (;;) {
    if (fs.existsSync(path.join(d, DEFAULT_OUT, 'graph.json'))) return { root: d, out: path.join(d, DEFAULT_OUT) };
    const up = path.dirname(d); if (up === d) break; d = up;
  }
  return { root: process.cwd(), out: path.join(process.cwd(), DEFAULT_OUT) };
}

function staleness(root, g) {
  const { files } = walk(root);
  const known = new Map(g.files.map((f) => [f.p, f]));
  const changed = [], added = [], removed = [];
  const seen = new Set();
  for (const f of files) {
    seen.add(f.path);
    const k = known.get(f.path);
    if (!k) added.push(f.path); else if (k.mtime !== f.mtime || k.size !== f.size) changed.push(f.path);
  }
  for (const f of g.files) if (!seen.has(f.p)) removed.push(f.p);
  return { changed, added, removed, any: changed.length + added.length + removed.length > 0 };
}

function loadGraph(args, { refresh = true } = {}) {
  const loc = locate(args);
  const gp = path.join(loc.out, 'graph.json');
  let note = '';
  if (!fs.existsSync(gp)) {
    const r = writeOutputs(loc.root, loc.out, { quiet: true });
    note = `(built graph: ${r.g.files.length} files)`;
    return { g: r.g, loc, note };
  }
  let g = JSON.parse(fs.readFileSync(gp, 'utf8'));
  if (refresh && args.refresh !== false) {
    const st = staleness(loc.root, g);
    if (st.any) {
      const r = writeOutputs(loc.root, loc.out, { quiet: true, instructions: false });
      note = `(graph refreshed: ${st.changed.length} changed, ${st.added.length} added, ${st.removed.length} removed)`;
      return { g: r.g, loc, note };
    }
  }
  return { g: indexGraph(g), loc, note };
}

function splitWords(s) { return s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2').toLowerCase().split(/[^a-z0-9]+/).filter(Boolean); }

function cmdFind(g, terms, limit) {
  terms = terms.flatMap((t) => [t.toLowerCase(), ...splitWords(t)]).filter((t, i, a) => t.length > 1 && a.indexOf(t) === i);
  if (!terms.length) return 'usage: find <words...>';
  const results = [];
  const scoreText = (name, p, extra) => {
    const nl = name.toLowerCase(), words = new Set(splitWords(name)), pl = p.toLowerCase(), el = extra.toLowerCase();
    let sc = 0, hit = 0;
    for (const t of terms) {
      let s = 0;
      if (nl === t) s = 10; else if (words.has(t)) s = 6; else if (nl.includes(t)) s = 4;
      if (pl.includes(t)) s = Math.max(s, 0) + 1.5;
      if (el.includes(t)) s += 1;
      if (s > 0) hit++;
      sc += s;
    }
    return hit ? sc * (hit / terms.length) * (hit === terms.length ? 1.5 : 1) : 0;
  };
  for (const s of g.syms) {
    const f = g.files[s.f];
    let sc = scoreText(s.n + ' ' + (s.o || ''), f.p, (s.sig || '') + ' ' + (s.doc || ''));
    if (!sc) continue;
    if (f.cat === 'test') sc *= 0.6;
    if (s.k === 'heading') sc *= 0.5;
    sc += Math.min(2, (g.callersOf.get(s.id) || []).length * 0.15);
    results.push({ sc, s });
  }
  for (let i = 0; i < g.files.length; i++) {
    const f = g.files[i];
    const sc = scoreText(f.p.slice(f.p.lastIndexOf('/') + 1).replace(/\.\w+$/, ''), f.p, f.sum) * 0.9;
    if (sc) results.push({ sc, f: i });
  }
  results.sort((a, b) => b.sc - a.sc);
  const out = [];
  for (const r of results.slice(0, limit)) {
    if (r.s) {
      const s = r.s, f = g.files[s.f];
      const callers = (g.callersOf.get(s.id) || []).length;
      out.push(`${f.p}:${range(s)}  ${KIND_ABBR[s.k] || s.k} ${s.sig ? clip(s.sig, 90) : symLabel(g, s)}${s.doc ? ' - ' + clip(s.doc, 70) : ''}${callers ? `  [${callers} ref${callers > 1 ? 's' : ''}]` : ''}`);
    } else {
      const f = g.files[r.f];
      out.push(`${f.p}  (file, ${f.lines} lines)${f.sum ? ' - ' + clip(f.sum, 90) : ''}  [used by ${g.in[r.f].length}, uses ${g.out[r.f].length}]`);
    }
  }
  return out.length ? out.join('\n') : `no matches for: ${terms.join(' ')}`;
}

function findFile(g, q) {
  q = toPosix(q).replace(/^\.\//, '');
  if (g.fileIdx.has(q)) return g.fileIdx.get(q);
  const ql = q.toLowerCase();
  const c = g.files.map((f, i) => ({ f, i })).filter(({ f }) => f.p.toLowerCase().endsWith('/' + ql) || f.p.toLowerCase() === ql);
  if (c.length) return c.sort((a, b) => a.f.p.length - b.f.p.length)[0].i;
  const d = g.files.map((f, i) => ({ f, i })).filter(({ f }) => f.p.toLowerCase().includes(ql));
  return d.length ? d.sort((a, b) => a.f.p.length - b.f.p.length)[0].i : -1;
}

function cmdFile(g, q) {
  const i = findFile(g, q);
  if (i < 0) return `no file matching "${q}"`;
  const f = g.files[i];
  const out = [`${f.p}  [${f.lang}, ${f.lines} lines]${f.sum ? '\n  ' + f.sum : ''}`];
  if (g.out[i].length) out.push('uses: ' + [...new Set(g.out[i])].map((j) => g.files[j].p).join(', '));
  if (g.in[i].length) out.push('used by: ' + [...new Set(g.in[i])].map((j) => g.files[j].p).join(', '));
  if (f.ext.length) out.push('external: ' + f.ext.join(', '));
  const syms = g.symsByFile[i];
  const depthOf = (s) => { let d = 0, p = s.p; while (p !== undefined) { d++; p = g.syms[p].p; } return d; };
  for (const s of syms) {
    const callers = (g.callersOf.get(s.id) || []).filter((c) => c.file !== i).length;
    out.push(`${'  '.repeat(depthOf(s) + 1)}${KIND_ABBR[s.k] || s.k} ${s.sig || symLabel(g, s)}  ${range(s)}${s.doc ? ' - ' + clip(s.doc, 80) : ''}${callers ? `  [used in ${callers} other file${callers > 1 ? 's' : ''}]` : ''}`);
  }
  return out.join('\n');
}

function cmdSym(g, name) {
  if (!name) return 'usage: sym <name>';
  const nl = name.toLowerCase().replace(/^.*(\.|::)/, '');
  const owner = name.includes('.') || name.includes('::') ? name.toLowerCase().split(/\.|::/).slice(-2, -1)[0] : null;
  let hits = g.syms.filter((s) => s.n.toLowerCase() === nl && (!owner || (s.o || (s.p !== undefined ? g.syms[s.p].n : '')).toLowerCase() === owner));
  if (!hits.length) hits = g.syms.filter((s) => s.n.toLowerCase().includes(nl)).slice(0, 15);
  if (!hits.length) return `no symbol "${name}". Try: find ${name}`;
  const out = [];
  for (const s of hits.slice(0, 10)) {
    const f = g.files[s.f];
    const parent = s.p !== undefined ? g.syms[s.p] : null;
    out.push(`* ${KIND_ABBR[s.k] || s.k} ${parent ? parent.n + '.' : ''}${symLabel(g, s)}  ${f.p}:${range(s)}`);
    if (s.sig) out.push('  ' + s.sig);
    if (s.doc) out.push('  ' + s.doc);
    const callers = g.callersOf.get(s.id) || [];
    if (callers.length) {
      out.push(`  referenced from (${callers.length}):`);
      for (const c of callers.slice(0, 25)) {
        const from = c.from >= 0 ? g.syms[c.from] : null;
        out.push(`    ${g.files[c.file].p}:${c.line}${from ? ' in ' + symLabel(g, from) + ` (${range(from)})` : ' (top level)'}${c.count > 1 ? ` x${c.count}` : ''}`);
      }
      if (callers.length > 25) out.push(`    ... +${callers.length - 25} more`);
    } else out.push('  no references found in indexed code');
    const callees = g.calleesOf.get(s.id) || [];
    if (callees.length) {
      out.push(`  uses (${callees.length}):`);
      for (const c of callees.slice(0, 20)) { const t = g.syms[c.to]; out.push(`    ${symLabel(g, t)}  ${g.files[t.f].p}:${range(t)}`); }
      if (callees.length > 20) out.push(`    ... +${callees.length - 20} more`);
    }
    const kids = g.symsByFile[s.f].filter((k) => k.p === s.id);
    if (kids.length) out.push('  members: ' + kids.map((k) => `${k.n} ${range(k)}`).join(' · '));
  }
  if (hits.length > 10) out.push(`... ${hits.length - 10} more matches`);
  return out.join('\n');
}

function cmdDeps(g, q, depth, reverse) {
  const i = findFile(g, q);
  if (i < 0) return `no file matching "${q}"`;
  const adj = reverse ? g.in : g.out;
  const out = [`${g.files[i].p} ${reverse ? 'is used by' : 'uses'} (depth ${depth}):`];
  const seen = new Set([i]);
  let frontier = [i];
  for (let d = 1; d <= depth && frontier.length; d++) {
    const next = [];
    for (const n of frontier) for (const m of new Set(adj[n])) if (!seen.has(m)) { seen.add(m); next.push(m); out.push(`${'  '.repeat(d)}${g.files[m].p}${d > 1 ? '' : ''}`); }
    frontier = next;
  }
  if (out.length === 1) out.push('  (none)');
  else out.push(`${seen.size - 1} file(s)` + (reverse ? '; tests among them: ' + [...seen].filter((k) => g.files[k].cat === 'test').length : ''));
  return out.join('\n');
}

// ───────────────────────────── main ─────────────────────────────

function main() {
  const args = parseArgs(process.argv.slice(2));
  const cmd = args._[0] || 'help';
  const rest = args._.slice(1);
  if (cmd === 'build') {
    const root = path.resolve(args.root || rest[0] || '.');
    const out = path.resolve(root, args.out || DEFAULT_OUT);
    const r = writeOutputs(root, out, args);
    const g = r.g;
    if (!args.quiet) {
      const rel = (p) => toPosix(path.relative(process.cwd(), p)) || '.';
      console.log(`codegraph ${VERSION}: ${g.files.length} files, ${g.syms.length} symbols, ${g.edges.length} file deps, ${g.refs.length} symbol refs in ${g.buildMs}ms`);
      console.log(`  agent map : ${rel(path.join(out, 'MAP.md'))} (~${r.mapInfo.tokens} tokens, level ${r.mapInfo.level}${r.mapInfo.split ? `, ${r.mapInfo.split} area files in map/` : ''})`);
      console.log(`  graph data: ${rel(path.join(out, 'graph.json'))}`);
      if (r.html) console.log(`  viewer    : ${rel(r.html)}`);
      console.log(`  query     : node ${rel(path.join(out, 'codegraph.js'))} find <words> | sym <name> | file <path> | rdeps <path>`);
      if (r.hooked.length) console.log(`  instructions updated: ${r.hooked.join(', ')}`);
      const w = g.warnings.filter(Boolean);
      if (w.length) console.log(`  warnings (${w.length}): ` + w.slice(0, 5).join('; ') + (w.length > 5 ? ' ...' : ''));
    }
    return;
  }
  if (cmd === 'stale') {
    const loc = locate(args);
    const gp = path.join(loc.out, 'graph.json');
    if (!fs.existsSync(gp)) return console.log('no graph yet - run: build');
    const st = staleness(loc.root, JSON.parse(fs.readFileSync(gp, 'utf8')));
    if (!st.any) return console.log('graph is up to date');
    for (const [k, v] of Object.entries({ changed: st.changed, added: st.added, removed: st.removed })) if (v.length) console.log(`${k} (${v.length}): ${v.slice(0, 30).join(', ')}${v.length > 30 ? ' ...' : ''}`);
    return;
  }
  if (['find', 'search', 'sym', 'symbol', 'who', 'callers', 'file', 'deps', 'rdeps', 'impact', 'stats'].includes(cmd)) {
    const { g, note } = loadGraph(args);
    if (note) console.log(note);
    const depth = Number(args.depth) || 2;
    let res;
    switch (cmd) {
      case 'find': case 'search': res = cmdFind(g, rest, Number(args.limit) || 25); break;
      case 'sym': case 'symbol': case 'who': case 'callers': res = cmdSym(g, rest.join(' ')); break;
      case 'file': res = cmdFile(g, rest.join(' ')); break;
      case 'deps': res = cmdDeps(g, rest.join(' '), depth, false); break;
      case 'rdeps': case 'impact': res = cmdDeps(g, rest.join(' '), depth, true); break;
      case 'stats': res = `${g.files.length} files, ${g.syms.length} symbols, ${g.edges.length} deps, ${g.refs.length} refs; built ${g.generated}`; break;
    }
    console.log(res);
    return;
  }
  console.log(fs.readFileSync(__filename, 'utf8').split('\n').slice(2, 16).map((l) => l.replace(/^ \* ?/, '')).join('\n'));
}

if (require.main === module) {
  try { main(); } catch (e) { console.error('codegraph error: ' + (e && e.stack || e)); process.exit(1); }
}
