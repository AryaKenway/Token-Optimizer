function extractDoc(rawLines, idx, lang, kind) {
  // comment lines directly above (skipping decorators/attributes)
  let j = idx - 1;
  while (j >= 0 && /^\s*(@[\w.]+|#\[|\[[A-Z]\w*)/.test(rawLines[j]) && !/^\s*\[.*\]\s*\(/.test(rawLines[j])) j--;
  const buf = [];
  while (j >= 0) {
    const t = rawLines[j].trim();
    if (/^(\/\/\/?|#(?!\[|!|include|define|if|endif|pragma|region)|--|\*|\/\*\*?|\*\/)/.test(t)) { buf.unshift(t); j--; } else break;
    if (buf.length > 12) break;
  }
  let text = buf.map((t) => t.replace(/^(\/\*\*?|\*\/|\/\/\/?|#+|--|\*)\s?/, '').replace(/\*\/$/, '').trim())
    .filter((t) => t && !/^@(param|returns?|throws|type|example|see)\b/.test(t)).join(' ');
  if (!text && lang === 'py' && kind !== 'const') {
    let sigDone = /:\s*(#.*)?$/.test(rawLines[idx]);
    for (let k = idx + 1; k < Math.min(rawLines.length, idx + 20); k++) {
      const t = rawLines[k].trim();
      if (!t) continue;
      if (!sigDone) { if (/:\s*(#.*)?$/.test(t)) sigDone = true; continue; }
      const m = /^[rRuUbB]?("""|''')\s*(.*)/.exec(t);
      if (m) text = m[2].replace(/("""|''').*$/, '').trim() || (rawLines[k + 1] || '').trim();
      break;
    }
  }
  text = text.replace(/\s+/g, ' ').trim();
  const sent = /^(.{12,}?[.!?])(\s|$)/.exec(text);
  return clip(sent ? sent[1] : text, 110);
}

function fileSummary(rawLines, lang, cat) {
  if (lang === 'md') {
    for (const l of rawLines.slice(0, 40)) { const t = l.trim(); if (t && !t.startsWith('#') && !t.startsWith('<') && !t.startsWith('!') && !t.startsWith('[') && !t.startsWith('```') && !t.startsWith('---') && t.length > 15) return clip(t.replace(/[*_`]/g, ''), 120); }
    const h = rawLines.find((l) => /^#\s/.test(l)); return h ? clip(h.replace(/^#+\s*/, ''), 120) : '';
  }
  if (cat === 'config') return '';
  const buf = [];
  let inBlock = false, inDoc = null;
  for (let i = 0; i < Math.min(rawLines.length, 60); i++) {
    let t = rawLines[i].trim();
    if (i === 0 && t.startsWith('#!')) continue;
    if (inDoc) { const end = t.indexOf(inDoc); buf.push(end >= 0 ? t.slice(0, end) : t); if (end >= 0) break; continue; }
    if (inBlock) { const end = t.includes('*/'); buf.push(t.replace(/\*\/.*$/, '').replace(/^\*\s?/, '')); if (end) { if (buf.join('').trim()) break; inBlock = false; } continue; }
    if (!t) { if (buf.join('').trim()) break; continue; }
    if (/^['"]use (strict|client|server)['"];?$/.test(t) || /^(#\s*-\*-|<\?php|package\s|\/\/\s*@ts-|\/\*\s*eslint|\/\/\s*eslint|#\s*(type|pylint|noqa|frozen_string)|\/\/\s*prettier)/.test(t)) continue;
    const dm = /^[rRuUbB]?("""|''')(.*)$/.exec(t);
    if (lang === 'py' && dm) { const rest = dm[2]; const end = rest.indexOf(dm[1]); if (end >= 0) { buf.push(rest.slice(0, end)); break; } buf.push(rest); inDoc = dm[1]; continue; }
    if (t.startsWith('/*')) { inBlock = !t.includes('*/'); buf.push(t.replace(/^\/\*+!?\s?/, '').replace(/\*\/.*$/, '')); if (!inBlock && buf.join('').trim()) break; continue; }
    const lm = /^(\/\/\/?!?|#+|--)\s?(.*)$/.exec(t);
    if (lm && !(lang === 'c' || lang === 'cpp') || (lm && !/^#\s*(include|define|if|pragma|ifndef|endif)/.test(t))) { buf.push(lm[2]); continue; }
    break;
  }
  let text = buf.map((s) => s.trim()).filter((s) => s && !/copyright|license|spdx|all rights reserved|^@author\b|^(author|created|date|version|modified|filename|file)\s*[:=]|^-+$|^=+$|^\*+$/i.test(s)).join(' ').replace(/\s+/g, ' ').trim();
  text = text.replace(/^@(file|fileoverview|module|overview)\s*/i, '');
  if (/^(using|import|#include|from|package|require)\b|[;{}]\s*$|;\s+\w/.test(text)) return ''; // commented-out code, not prose
  const sent = /^(.{20,}?[.!?])(\s|$)/.exec(text);
  return clip(sent ? sent[1] : text, 140);
}

function buildSignature(rawLines, codeLines, idx, lang) {
  let s = '', depth = 0, seenParen = false;
  for (let k = idx; k < Math.min(codeLines.length, idx + 8); k++) {
    const c = codeLines[k], r = rawLines[k];
    let cut = r.length;
    for (let q = 0; q < c.length; q++) {
      const ch = c[q];
      if (ch === '(') { depth++; seenParen = true; } else if (ch === ')') depth--;
      else if (depth === 0 && (ch === '{' || (ch === ':' && lang === 'py' && seenParen) || (ch === '=' && c[q + 1] === '>' && seenParen))) { cut = q; break; }
    }
    s += (s ? ' ' : '') + r.slice(0, cut).trim();
    if (cut < r.length || (seenParen && depth <= 0) || (!seenParen && k === idx && !/[(,]\s*$/.test(c))) break;
  }
  s = s.replace(/^\s*(export\s+)?(default\s+)?/, '').replace(/\s+/g, ' ').replace(/\s*[{:]\s*$/, '').trim();
  return clip(s, 120);
}

function computeBraces(code) {
  const match = new Map();
  const stack = [];
  for (let i = 0; i < code.length; i++) {
    const c = code.charCodeAt(i);
    if (c === 123) stack.push(i);
    else if (c === 125 && stack.length) match.set(stack.pop(), i);
  }
  return match;
}
function lineDepths(code, nLines) {
  const d = new Int32Array(nLines + 1);
  let depth = 0, line = 0;
  d[0] = 0;
  for (let i = 0; i < code.length; i++) {
    const c = code.charCodeAt(i);
    if (c === 10) { line++; d[line] = depth; } else if (c === 123) depth++; else if (c === 125 && depth > 0) depth--;
  }
  return d;
}

function findBodyEnd(code, starts, braces, idx, { allowArrow = true } = {}) {
  // From the start of line idx, find the first '{' before a terminating ';' (at paren depth 0).
  const from = starts[idx];
  const limit = Math.min(code.length, from + 1500);
  let pd = 0;
  for (let p = from; p < limit; p++) {
    const ch = code[p];
    if (ch === '(' || ch === '[') pd++;
    else if (ch === ')' || ch === ']') pd--;
    else if (pd <= 0 && ch === ';') return { end: lineOfPos(starts, p), body: false };
    else if (ch === '{') {
      const close = braces.get(p);
      if (close === undefined) return null;
      return { end: lineOfPos(starts, close), body: true };
    } else if (pd <= 0 && allowArrow && ch === '=' && code[p + 1] === '>') {
      // expression-bodied arrow: continue to first '{' or ';' / newline at depth 0
      let q = p + 2; while (q < limit && /\s/.test(code[q])) q++;
      if (code[q] === '{') { const close = braces.get(q); if (close !== undefined) return { end: lineOfPos(starts, close), body: true }; }
      if (code[q] === '(') { // => ( ... )
        let dd = 0; for (let r = q; r < code.length && r < q + 20000; r++) { if (code[r] === '(') dd++; else if (code[r] === ')' && --dd === 0) return { end: lineOfPos(starts, r), body: true }; }
      }
      let r = q; while (r < code.length && r < q + 4000 && code[r] !== ';' && code[r] !== '\n') r++;
      return { end: lineOfPos(starts, r), body: true };
    }
  }
  return null;
}

function indentOf(s) { const m = /^[ \t]*/.exec(s)[0]; return m.replace(/\t/g, '    ').length; }

function extractSymbols(f, raw, codeText) {
  const lang = f.lang;
  const rawLines = raw.split('\n');
  const codeLines = codeText.split('\n');
  const n = rawLines.length;
  const syms = [];
  const push = (s) => { s.doc = s.doc ?? extractDoc(rawLines, s.line - 1, lang, s.kind); syms.push(s); return s; };

  if (lang === 'md') {
    let fence = false;
    for (let i = 0; i < n; i++) {
      if (/^\s*```/.test(rawLines[i])) fence = !fence;
      const m = !fence && /^(#{1,3})\s+(.+?)\s*#*\s*$/.exec(rawLines[i]);
      if (m) syms.push({ name: clip(m[2].replace(/[*_`]/g, ''), 80), kind: 'heading', line: i + 1, end: i + 1, level: m[1].length, sig: '', doc: '' });
    }
    for (let k = 0; k < syms.length; k++) {
      let e = n;
      for (let q = k + 1; q < syms.length; q++) if (syms[q].level <= syms[k].level) { e = syms[q].line - 1; break; }
      syms[k].end = Math.max(syms[k].line, e);
    }
    return syms;
  }
  if (lang === 'make') {
    for (let i = 0; i < n; i++) { const m = /^([A-Za-z0-9_.\-/]+)\s*:(?!=)/.exec(rawLines[i]); if (m && !m[1].startsWith('.')) syms.push({ name: m[1], kind: 'target', line: i + 1, end: i + 1, sig: '', doc: '' }); }
    for (let k = 0; k < syms.length; k++) { let e = (k + 1 < syms.length ? syms[k + 1].line - 1 : n); while (e > syms[k].line && !rawLines[e - 1].trim()) e--; syms[k].end = e; }
    return syms;
  }
  if (lang === 'pkgjson') {
    let inScripts = false;
    for (let i = 0; i < n; i++) {
      if (/^\s*"scripts"\s*:\s*\{/.test(rawLines[i])) { inScripts = true; continue; }
      if (inScripts) { if (/^\s*\}/.test(rawLines[i])) break; const m = /^\s*"([^"]+)"\s*:\s*"(.*)"/.exec(rawLines[i]); if (m) syms.push({ name: m[1], kind: 'script', line: i + 1, end: i + 1, sig: clip(`${m[1]}: ${m[2].replace(/\\"/g, '"').replace(/\\\\/g, '\\')}`, 100), doc: '' }); }
    }
    return syms;
  }
  if (lang === 'css' || f.cat === 'config') return syms;

  const rules = RE[lang] || [];
  const memberRules = LANG_MEMBER[lang] ? RE[LANG_MEMBER[lang]] : null;
  const indentLang = lang === 'py' || lang === 'ruby' || lang === 'lua';

  if (indentLang) {
    const stack = []; // {sym, indent}
    for (let i = 0; i < n; i++) {
      const line = codeLines[i];
      if (!line.trim()) continue;
      const ind = indentOf(line);
      while (stack.length && ind <= stack[stack.length - 1].indent && !(lang !== 'py' && /^\s*end\b/.test(line) && ind === stack[stack.length - 1].indent && false)) stack.pop();
      for (const [re, kind0, opt = {}] of rules) {
        const m = re.exec(line);
        if (!m) continue;
        const name = m[opt.nameGroup || 2];
        let kind = opt.kindGroup ? m[opt.kindGroup].toLowerCase() : kind0;
        if (kind === 'module' || kind === 'class') kind = kind === 'module' ? 'module' : 'class';
        if (opt.depth0 && ind > 0) continue;
        const parent = stack.length ? stack[stack.length - 1].sym : null;
        if (parent && !CONTAINER_KINDS.has(parent.kind)) break; // nested inside a function: skip
        if (kind === 'function' && parent && CONTAINER_KINDS.has(parent.kind)) kind = 'method';
        let end = i + 1;
        if (!opt.oneLine) {
          if (opt.rubyEnd && lang !== 'py') {
            // find matching `end` at same indent; one-liners (def x = ..; end on same line) handled by fallback
            if (/\bend\s*$/.test(line) && !/^\s*(class|module)\b/.test(line)) end = i + 1;
            else for (let k = i + 1; k < n; k++) { const t = codeLines[k]; if (t.trim() && indentOf(t) <= ind) { end = /^\s*end\b/.test(t) && indentOf(t) === ind ? k + 1 : k; break; } end = k + 1; }
          } else {
            end = i + 1;
            for (let k = i + 1; k < n; k++) { const t = codeLines[k]; if (!t.trim()) continue; if (indentOf(t) <= ind && !/^\s*[)\]}]/.test(t)) break; end = k + 1; }
          }
        }
        const s = push({ name, kind, line: i + 1, end, sig: kind === 'const' ? '' : buildSignature(rawLines, codeLines, i, lang), parent });
        if (lang === 'ruby' && /^self\./.test(name)) s.name = name.slice(5);
        if (lang === 'py') s.exported = !name.startsWith('_');
        if (!opt.oneLine) stack.push({ sym: s, indent: ind });
        break;
      }
    }
  } else {
    const starts = lineStartsOf(codeText);
    const braces = computeBraces(codeText);
    const depths = lineDepths(codeText, n);
    const open = []; // container stack {sym, depth}
    for (let i = 0; i < n; i++) {
      const line = codeLines[i];
      if (!line.trim()) continue;
      const d = depths[i];
      while (open.length && open[open.length - 1].sym.end < i + 1) open.pop();
      const encl = open.length ? open[open.length - 1] : null;
      // skip lines nested inside a function body
      if (encl && !CONTAINER_KINDS.has(encl.sym.kind)) continue;
      const inClass = encl && CONTAINER_KINDS.has(encl.sym.kind) && encl.sym.kind !== 'namespace' && encl.sym.kind !== 'module';
      if (encl && d > encl.depth + 1) continue; // deeper than direct members
      let matched = false;
      const tryRules = (ruleList, member) => {
        for (const [re, kind0, opt = {}] of ruleList) {
          if (opt.depth0 && d !== 0) continue;
          if (opt.inBlock) continue;
          const m = re.exec(line);
          if (!m) continue;
          let name = m[opt.nameGroup || 1];
          if (!name) continue;
          if (opt.route) { const rm = re.exec(rawLines[i]); if (!rm) continue; name = rm[1].toUpperCase() + ' ' + rm[2]; }
          let kind = opt.kindGroup ? m[opt.kindGroup].toLowerCase().replace(/\s+class$/, '').replace('@interface', 'interface') : kind0;
          if (kind === 'record' || kind === 'union' || kind === 'actor' || kind === 'mixin') kind = kind === 'union' ? 'struct' : 'class';
          if (CONTROL.has(name) || CONTROL.has(name.replace(/^.*::/, ''))) continue;
          if (member && encl && name === encl.sym.name && lang === 'cpp') kind = 'method';
          let owner = opt.owner ? m[opt.owner] : undefined;
          if (opt.qualified && name.includes('::')) { const parts = name.split('::'); name = parts.pop(); owner = parts.join('::'); kind = 'method'; }
          if (lang === 'cpp' && !member && kind === 'function' && /^\s/.test(line) && !encl) continue; // indented, likely a call/statement
          let end = i + 1, hasBody = true;
          if (!opt.oneLine) {
            const r = findBodyEnd(codeText, starts, braces, i, { allowArrow: lang === 'js' || lang === 'ts' || lang === 'csharp' || lang === 'dart' });
            if (opt.sqlEnd) { let k = i; while (k < n && !codeLines[k].includes(';')) k++; end = Math.min(n, k + 1); }
            else if (r) { end = r.end; hasBody = r.body; } else if (opt.body) continue;
            if (opt.body && !hasBody) continue; // declaration / call, not definition
            if ((kind === 'function' || kind === 'method') && !hasBody && (lang === 'java' || lang === 'csharp' || lang === 'cpp' || lang === 'c')) continue;
          }
          if (kind === 'function' && inClass) kind = 'method';
          if (member) kind = 'method';
          const s = push({ name, kind, line: i + 1, end: Math.max(end, i + 1), sig: (kind === 'const' || kind === 'macro') ? clip(line.trim(), 90) : buildSignature(rawLines, codeLines, i, lang), parent: encl ? encl.sym : null });
          if (s.kind === 'macro' || s.kind === 'const') s.sig = clip(rawLines[i].trim().replace(/\s+/g, ' '), 90);
          if (owner) s.owner = owner;
          if (lang === 'js' || lang === 'ts') s.exported = /^\s*export\b|exports\./.test(rawLines[i]);
          else if (lang === 'go') s.exported = /^[A-Z]/.test(name);
          else if (lang === 'rust') s.exported = /^\s*pub\b/.test(rawLines[i]);
          else if (lang === 'java' || lang === 'csharp' || lang === 'kotlin' || lang === 'swift') s.exported = !/\bprivate\b/.test(rawLines[i]);
          if (CONTAINER_KINDS.has(kind) || kind === 'function' || kind === 'method' || kind === 'route') if (end > i + 1 || hasBody) open.push({ sym: s, depth: d });
          matched = true;
          return true;
        }
        return false;
      };
      if (inClass && memberRules && lang !== 'cpp') { if (tryRules(rules, false) || tryRules(memberRules, true)) continue; }
      else if (inClass && lang === 'cpp') { if (tryRules(rules, false) || tryRules(memberRules, true)) continue; }
      else tryRules(rules, false);
      if (!matched && lang === 'go' && encl == null) { /* nothing */ }
    }
  }
  for (const s of syms) {
    if (s.kind === 'route') { s.sig = s.name; continue; }
    if (s.kind === 'function' || s.kind === 'method') {
      for (let k = s.line - 2; k >= Math.max(0, s.line - 8); k--) {
        const t = rawLines[k].trim();
        if (!t.startsWith('@') && !t.startsWith('[')) break;
        const m = ROUTE_ANNOTATIONS.map((re) => re.exec(t)).find(Boolean);
        if (m) { s.route = `${m[1].toUpperCase()} ${m[2] || ''}`.trim(); break; }
      }
    }
    if (s.sig) s.sig = cleanSig(s.sig);
  }
  return syms;
}

const ROUTE_ANNOTATIONS = [
  /^@(?:[\w.]+\.)?(get|post|put|patch|delete|route|api_route|websocket|head|options)\s*\(\s*(?:path\s*=\s*)?['"]([^'"]*)['"]/i,
  /^@(Get|Post|Put|Patch|Delete|Request|Message|Subscribe)Mapping\s*\(\s*(?:(?:value|path)\s*=\s*)?\{?\s*"([^"]*)"/,
  /^\[Http(Get|Post|Put|Patch|Delete)(?:\s*\(\s*"([^"]*)")?/,
];
const SIG_DROP = new Set('export default declare public pub internal function def fn func fun class interface enum struct trait type namespace module impl const let var record object protocol extension async'.split(' '));
function cleanSig(sig) {
  let s = sig.replace(/^impl\s*<[^{]*?>\s*/, 'impl ');
  for (;;) { const m = /^(pub\([^)]*\)|[A-Za-z_]+)\s+/.exec(s); if (!m || !SIG_DROP.has(m[1].replace(/\(.*/, ''))) break; s = s.slice(m[0].length); }
  s = s.replace(/^([A-Za-z_$][\w$]*)\s*(?::[^=()]+)?=\s*(?:async\s+)?(?:function\s*\*?\s*)?\(/, '$1(');
  s = s.replace(/^([A-Za-z_]\w*(?:\[[^\]]*\])?)\s+(struct|interface)$/, '$1');
  s = s.replace(/\(\s*(self|cls)\s*(,\s*|\))/, (m0, w, rest) => (rest === ')' ? '()' : '('));
  return s.replace(/\(\s+/g, '(').replace(/\s+\)/g, ')').replace(/\s+,/g, ',');
}

